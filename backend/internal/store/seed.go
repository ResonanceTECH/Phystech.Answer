func seedUser(ctx context.Context, st Store, u model.User, hash string) (model.User, error) {
	user, err := st.CreateUser(ctx, u, hash)
	if errors.Is(err, ErrConflict) {
		return model.User{}, nil
	}
	return user, err
}
